'use strict';
// Compiles build/uninstaller/Uninstaller.cs into
// build/uninstaller/bin/Uninstall Mod Command X.exe with the C# compiler that
// ships inside the .NET Framework 4.x of every Windows 10/11
// (%WINDIR%\Microsoft.NET\Framework64\v4.0.30319\csc.exe). The result is a
// ~60 KB WinForms exe that needs no extra runtime and no admin rights — see
// README "Uninstalling" for why it is not a second Electron app.
//
// Runs automatically from electron-builder's beforePack hook (build/before-pack.js)
// for Windows builds; `npm run build-uninstaller` runs it alone.
// Exits 0 without building on non-Windows hosts (the Linux AppImage ships
// build/uninstaller/uninstall-linux.sh instead).

const fs = require('fs');
const path = require('path');
const { spawnSync } = require('child_process');

const ROOT = path.resolve(__dirname, '..');
const SRC_DIR = path.join(__dirname, 'uninstaller');
const OUT_DIR = path.join(SRC_DIR, 'bin');
const OBJ_DIR = path.join(SRC_DIR, 'obj');
const EXE_NAME = 'Uninstall Mod Command X.exe';
const OUT_EXE = path.join(OUT_DIR, EXE_NAME);

function findCsc() {
  const win = process.env.WINDIR || process.env.SystemRoot || 'C:\\Windows';
  for (const fw of ['Framework64', 'Framework']) {
    const p = path.join(win, 'Microsoft.NET', fw, 'v4.0.30319', 'csc.exe');
    if (fs.existsSync(p)) return p;
  }
  return null;
}

// archiveName / out: test-only overrides (e.g. compiling a variant for a
// shared-archive build before lib/storage.js changes).
function build({ quiet, archiveName, out } = {}) {
  if (process.platform !== 'win32') {
    if (!quiet) console.log('  • uninstaller: not a Windows host — skipped (Linux uses uninstall-linux.sh)');
    return null;
  }
  const csc = findCsc();
  if (!csc) throw new Error('csc.exe (.NET Framework 4.x) not found — it ships with Windows 10/11; is the .NET Framework 4.8 feature disabled?');

  // The archive folder name comes from the app's own code, never a copy.
  const ARCHIVE_DIR_NAME = archiveName || require(path.join(ROOT, 'lib', 'storage.js')).ARCHIVE_DIR_NAME;
  const outExe = out ? path.resolve(out) : OUT_EXE;
  const pkg = JSON.parse(fs.readFileSync(path.join(ROOT, 'package.json'), 'utf8'));
  if (!/^[\w .-]+$/.test(ARCHIVE_DIR_NAME)) throw new Error(`unexpected ARCHIVE_DIR_NAME ${JSON.stringify(ARCHIVE_DIR_NAME)}`);
  const ver = String(pkg.version || '1.0.0').replace(/[^\d.]/g, '') || '1.0.0';
  fs.mkdirSync(OBJ_DIR, { recursive: true });
  fs.mkdirSync(path.dirname(outExe), { recursive: true });
  const buildInfo = path.join(OBJ_DIR, 'BuildInfo.cs');
  fs.writeFileSync(buildInfo, [
    '// Generated by build/build-uninstaller.js — do not edit.',
    `[assembly: System.Reflection.AssemblyVersion("${ver}.0")]`,
    `[assembly: System.Reflection.AssemblyFileVersion("${ver}.0")]`,
    // 4.6.2+ path handling = no MAX_PATH limit (with the manifest's longPathAware);
    // runs on the .NET Framework 4.8 built into Windows 10 1903+ / 11.
    '[assembly: System.Runtime.Versioning.TargetFramework(".NETFramework,Version=v4.6.2")]',
    'namespace ModCommandXUninstaller {',
    '  static class BuildInfo {',
    `    public const string ArchiveDirName = ${JSON.stringify(ARCHIVE_DIR_NAME)}; // lib/storage.js ARCHIVE_DIR_NAME`,
    `    public const string AppVersion = ${JSON.stringify(pkg.version)};`,
    '  }',
    '}',
    '',
  ].join('\r\n'));

  const args = [
    '/nologo', '/target:winexe', '/optimize+', '/platform:anycpu', '/langversion:5',
    `/win32icon:${path.join(__dirname, 'icon.ico')}`,
    `/win32manifest:${path.join(SRC_DIR, 'app.manifest')}`,
    `/out:${outExe}`,
    '/r:System.dll', '/r:System.Core.dll', '/r:System.Drawing.dll', '/r:System.Windows.Forms.dll',
    '/r:System.Web.Extensions.dll', '/r:System.Management.dll',
    path.join(SRC_DIR, 'Uninstaller.cs'), buildInfo,
  ];
  const r = spawnSync(csc, args, { encoding: 'utf8', windowsHide: true });
  if (r.status !== 0) {
    throw new Error(`csc.exe failed (exit ${r.status}):\n${String(r.stdout || '')}${String(r.stderr || '')}`);
  }
  const size = fs.statSync(outExe).size;
  if (!quiet) console.log(`  • uninstaller built: ${path.relative(ROOT, outExe)} (${(size / 1024).toFixed(0)} KB, archive folder "${ARCHIVE_DIR_NAME}")`);
  return outExe;
}

module.exports = { build, OUT_EXE, EXE_NAME };

if (require.main === module) {
  const opt = (f) => { const i = process.argv.indexOf(f); return i !== -1 ? process.argv[i + 1] : undefined; };
  try {
    build({ archiveName: opt('--archive-name'), out: opt('--out') });
    const i = process.argv.indexOf('--copy-to');
    if (i !== -1 && process.argv[i + 1] && fs.existsSync(OUT_EXE)) {
      fs.mkdirSync(process.argv[i + 1], { recursive: true });
      fs.copyFileSync(OUT_EXE, path.join(process.argv[i + 1], EXE_NAME));
      console.log(`  • copied to ${path.join(process.argv[i + 1], EXE_NAME)}`);
    }
  } catch (e) {
    console.error('uninstaller build failed:', e.message);
    process.exit(1);
  }
}
